World.Music = new class {
  constructor(){
    this.songs={} //song database
    this.time=0
    this.track=void 0 //current
    this.tInx=-1 //tracks currentInx //temp value to align
    World.TickTask.musicStart=this.start.bind(this)
  }
  start(){
    this.next()
    delete World.TickTask.musicStart
  }
  //dispatch to TickTask
  play(key){
    this.track = this.songs[key]
    this.time = 0
    this.track.mod ??= [0,1,[0]]
    World.TickTask.music=this._playStep.bind(this)
  }
  next(){
    let keys = Reflect.ownKeys(this.songs)
    this.tInx+=1
    this.tInx%=keys.length
    let name = keys[this.tInx]
    api.broadcastMessage(`[BackBeats]: Now Playing: ${name}`,{color:"orange"})
    this.play(name)
  }
  _playStep(){
    this.time = Math.round(this.time * 100) / 100 //no fpe
    let notes = this.track[this.time]
    if(this.time > this.track.len){delete World.TickTask.music;this.next();return}
    if(notes==void 0){this.time+=.05;return}
    let mod = this.track.mod
    notes.map(e=>{
      let [s,v,p] = e
      mod[2].map(e=>{
        api.broadcastSound(this.track.instr[s],v*mod[1],p*(2**e))
      })
    })
    this.time+=.05 //tick
  }
}

