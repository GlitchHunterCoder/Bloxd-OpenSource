function loadLevels(levelData) {
  for (const id in levelData) {
    const raw = levelData[id];
    Backroom.Levels.add(new Level({
      levelId:   id,
      levelName: raw.name,
      spawn:     raw.spawn.default ?? null,
      landmarks: raw.landmarks,
      exit:      [],
      enter:     [],
    }));
  }
  for (const id in levelData) {
    const raw    = levelData[id];
    const source = Backroom.Levels[id];
    for (const exitId of raw.exits) {
      const target = Backroom.Levels[exitId];
      if (!target) {
        console.log(`LevelLoader: exit "${exitId}" from "${id}" has no matching level — skipping edge`);
        continue;
      }
      const spawnOverride = raw.spawn.origins[exitId]
                         ?? target.spawn?.origins?.[id]
                         ?? null;
      source.exit.push(new Edge(target, spawnOverride));
      target.enter.push(new Edge(source, null));
    }
  }
}

